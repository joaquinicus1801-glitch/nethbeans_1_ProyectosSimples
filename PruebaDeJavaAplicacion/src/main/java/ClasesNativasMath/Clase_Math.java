
package ClasesNativasMath;


public class Clase_Math {

    public static void main(String[] args) {
        Math.sqrt(64); //saca la raiz cuadrada de ese numero
        Math.abs(-98); //te da el valor absoluto de  ese numero
        Math.pow(43,2); //es para hacer potencias el primere argumento es el numero a potenciar y el segundo es el numero portenciador
        Math.atan(4/6); //te da erl arcotangente de la expesion o valor que ingreses
        Math.round(4.67); //redonde el numero, si el decimal supera los 0.5 entonces lo volevera el entero mas cercano
        Math.toDegrees(52); //convierte de radianes a degrees osea grados, ideal para calcular angulos de una figura por ejemplo
    }
    
}
